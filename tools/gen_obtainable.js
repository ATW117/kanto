#!/usr/bin/env node
// Generates crates/kanto-env/src/data/obtainable.rs: what Showdown's `[Gen 1] OU` validator needs
// beyond the learnset union (Gen 1 move sources with levels, Gen 1 events, lowest Gen 1 encounter
// levels, evolution levels, the "Obtainable Moves" combination bans).
//
// Usage: node tools/gen_obtainable.js <pokemon-showdown dir> > crates/kanto-env/src/data/obtainable.rs
'use strict';
const path = require('path');
const psDir = process.argv[2];
const {TeamValidator, Dex} = require(path.resolve(psDir, 'dist/sim'));
const version = require(path.resolve(psDir, 'package.json')).version;
const v = TeamValidator.get('gen1ou');
const d = Dex.forFormat(v.format);
const lit = s => JSON.stringify(s);
const out = [];
const w = s => out.push(s);
w(`// @generated by tools/gen_obtainable.js from pokemon-showdown ${version} (TeamValidator('gen1ou')). Do not edit.`);
w('#![allow(clippy::all)]');
w('');
w('/// Per Gen 1 species (index = dex number; 0 unused).');
w('pub struct Obtain {');
w('    pub id: &\'static str,');
w('    pub name: &\'static str,');
w('    /// Lowest Gen 1 encounter level (0 = no Gen 1 encounter data).');
w('    pub encounter: u8,');
w('    /// `species.evoLevel` (0 = none) and `species.prevo` (id, "" = none).');
w('    pub evo_level: u8,');
w('    pub prevo: &\'static str,');
w('    /// (move id, Gen 1 sources) for every move with a Gen 1 source, sources in Showdown\'s order.');
w('    pub moves: &\'static [(&\'static str, &\'static [&\'static str])],');
w('}');
w('');
w('pub static OBTAIN: [Obtain; 152] = [');
w('    Obtain { id: "", name: "", encounter: 0, evo_level: 0, prevo: "", moves: &[] },');
for (let n = 1; n <= 151; n++) {
  const sp = d.species.all().find(s => s.num === n && !s.forme);
  const ls = d.species.getLearnsetData(sp.id);
  let enc = 0;
  for (const e of ls.encounters || []) {
    if (e.generation !== 1 || !e.level) continue;
    if (enc && e.level > enc) continue;
    enc = e.level;
  }
  const moves = [];
  for (const [m, srcs] of Object.entries(ls.learnset || {})) {
    const g1 = srcs.filter(s => s.charAt(0) === '1');
    if (g1.length) moves.push(`(${lit(m)}, &[${g1.map(lit).join(', ')}])`);
  }
  const prevo = sp.prevo ? toId(sp.prevo) : '';
  w(`    Obtain { id: ${lit(sp.id)}, name: ${lit(sp.name)}, encounter: ${enc}, evo_level: ${sp.evoLevel || 0}, prevo: ${lit(prevo)}, moves: &[${moves.join(', ')}] },`);
}
w('];');
function toId(s) { return s.toLowerCase().replace(/[^a-z0-9]/g, ''); }
w('');
w('/// Gen 1 events: (species id, event index, level, Japan-only, moves).');
const evs = [];
for (const sp of d.species.all()) {
  if (sp.num < 1 || sp.num > 151 || sp.forme) continue;
  const ls = d.species.getLearnsetData(sp.id);
  (ls.eventData || []).forEach((e, i) => {
    if (e.generation !== 1) return;
    evs.push(`(${lit(sp.id)}, ${i}, ${e.level || 0}, ${!!e.japan}, &[${(e.moves || []).map(lit).join(', ')}])`);
  });
}
w(`pub static EVENTS: [(&str, u8, u8, bool, &[&str]); ${evs.length}] = [${evs.join(', ')}];`);
w('');
w('/// `[Gen 1] OU` complex bans: (rule, parts as "pokemon:id" / "basepokemon:id" / "move:id").');
const cb = v.ruleTable.complexBans.filter(c => c[3].every(p => /^(pokemon|basepokemon|move):/.test(p)));
w(`pub static COMBO_BANS: [(&str, &str, &[&str]); ${cb.length}] = [${cb.map(c => `(${lit(c[0])}, ${lit(c[1])}, &[${c[3].map(lit).join(', ')}])`).join(', ')}];`);
process.stdout.write(out.join('\n') + '\n');
