#!/usr/bin/env node
// Generates crates/sim-data/src/gen1.rs from pokemon-showdown's resolved gen1 dex.
//
// Usage: node tools/gen_sim_data.js <path to pokemon-showdown package> > crates/sim-data/src/gen1.rs
//
// Everything that is plain data (stats, types, move numbers, secondaries, flags, the type chart and
// Metronome's move list) comes from Showdown's `Dex.mod('gen1')` with inheritance resolved, so the
// tables are exactly what Showdown 0.11.11 uses. Move *callbacks* are hand-written in sim-gen1.
'use strict';
const path = require('path');
const psDir = process.argv[2];
if (!psDir) {
  console.error('usage: gen_sim_data.js <pokemon-showdown dir>');
  process.exit(2);
}
const {Dex} = require(path.resolve(psDir, 'dist/sim'));
const version = require(path.resolve(psDir, 'package.json')).version;
const d = Dex.mod('gen1');

// pkmn/engine's type order (keeps ids compatible with battle-env's observation encoding).
const TYPES = ['Normal', 'Fighting', 'Flying', 'Poison', 'Ground', 'Rock', 'Bug', 'Ghost', 'Fire', 'Water',
  'Grass', 'Electric', 'Psychic', 'Ice', 'Dragon'];
const TYPELESS = TYPES.length; // '???'
for (const t of TYPES) if (!d.types.get(t).exists) throw new Error(`missing type ${t}`);
const typeId = t => (t === '???' ? TYPELESS : (() => {
  const i = TYPES.indexOf(t); if (i < 0) throw new Error(`type ${t}`); return i;
})());

const STATUS = ['', 'slp', 'psn', 'brn', 'frz', 'par', 'tox'];
const VOLATILES = ['', 'partiallytrapped', 'partialtrappinglock', 'confusion', 'flinch', 'disable', 'mist',
  'leechseed', 'lightscreen', 'reflect', 'focusenergy', 'bide', 'substitute', 'minimize', 'defensecurl',
  'lockedmove', 'mustrecharge', 'rage'];
const TARGETS = ['normal', 'self', 'any', 'randomNormal', 'allAdjacentFoes', 'allAdjacent', 'scripted'];
const CATS = ['Physical', 'Special', 'Status'];
const BOOSTS = ['atk', 'def', 'spa', 'spd', 'spe', 'accuracy', 'evasion'];
const idx = (list, v, what) => {
  const i = list.indexOf(v || '');
  if (i < 0) throw new Error(`unknown ${what} ${v}`);
  return i;
};
const boosts = b => `[${BOOSTS.map(k => (b && b[k]) || 0).join(', ')}]`;

const out = [];
const w = s => out.push(s);
w(`// @generated by tools/gen_sim_data.js from pokemon-showdown ${version} (Dex.mod('gen1')).`);
w('// Do not edit by hand.');
w('#![allow(clippy::all)]');
w('use crate::{MoveData, Secondary, SpeciesData};');
w('');
w(`pub const SHOWDOWN_VERSION: &str = ${JSON.stringify(version)};`);
w(`pub const NUM_TYPES: usize = ${TYPES.length};`);
w(`/// The typeless "???" type (Struggle, Bide, Gen 1's thawed "nomove").`);
w(`pub const TYPELESS: u8 = ${TYPELESS};`);
w(`pub static TYPE_NAMES: [&str; ${TYPES.length + 1}] = ${JSON.stringify([...TYPES, '???'])};`);
w('');
w('/// `getEffectiveness(attack, defend)`: -1 resisted, 0 neutral, 1 super effective (per defending type).');
w(`pub static EFFECTIVENESS: [[i8; ${TYPES.length}]; ${TYPES.length}] = [`);
for (const a of TYPES) w(`    [${TYPES.map(t => d.getEffectiveness(a, t)).join(', ')}],`);
w('];');
w('/// `!getImmunity(attack, defend)`: the defending type is immune to the attacking type.');
w(`pub static IMMUNE: [[bool; ${TYPES.length}]; ${TYPES.length}] = [`);
for (const a of TYPES) w(`    [${TYPES.map(t => !d.getImmunity(a, t)).join(', ')}],`);
w('];');
w('');
w('pub mod status {');
STATUS.forEach((s, i) => w(`    pub const ${(s || 'none').toUpperCase()}: u8 = ${i};`));
w(`    pub static IDS: [&str; ${STATUS.length}] = ${JSON.stringify(STATUS)};`);
w('}');
w('pub mod vol {');
VOLATILES.forEach((s, i) => w(`    pub const ${(s || 'none').toUpperCase()}: u8 = ${i};`));
w(`    pub static IDS: [&str; ${VOLATILES.length}] = ${JSON.stringify(VOLATILES)};`);
w('}');
w('pub mod target {');
TARGETS.forEach((s, i) => w(`    pub const ${s.replace(/[A-Z]/g, c => '_' + c).toUpperCase()}: u8 = ${i};`));
w('}');
w('');

// Species
const species = d.species.all().filter(s => s.num >= 1 && s.num <= 151 && !s.forme).sort((a, b) => a.num - b.num);
if (species.length !== 151) throw new Error('expected 151 species');
w(`pub const NUM_SPECIES: usize = 151;`);
w('/// Index = National Dex number (pkmn/engine species id); index 0 is unused.');
w('pub static SPECIES: [SpeciesData; 152] = [');
w('    SpeciesData { id: "", name: "None", types: [0, 0], base: [0; 6] },');
for (const s of species) {
  const t = s.types.map(typeId);
  const b = s.baseStats;
  w(`    SpeciesData { id: ${JSON.stringify(s.id)}, name: ${JSON.stringify(s.name)}, types: [${t[0]}, ${t[1] ?? t[0]}], base: [${b.hp}, ${b.atk}, ${b.def}, ${b.spa}, ${b.spd}, ${b.spe}] },`);
}
w('];');
w('');

// Moves
const moves = d.moves.all().filter(m => m.num >= 1 && m.num <= 165).sort((a, b) => a.num - b.num);
if (moves.length !== 165) throw new Error('expected 165 moves');
w('pub const NUM_MOVES: usize = 165;');
w('pub mod mv {');
for (const m of moves) w(`    pub const ${m.id.toUpperCase()}: u8 = ${m.num};`);
w('}');
w('/// Index = move number (pkmn/engine move id); index 0 is unused.');
w('pub static MOVES: [MoveData; 166] = [');
w('    MoveData::NONE,');
for (const m of moves) {
  const sec = m.secondaries && m.secondaries[0];
  if (m.secondaries && m.secondaries.length > 1) throw new Error(`multiple secondaries ${m.id}`);
  let multihit = 0;
  if (Array.isArray(m.multihit)) {
    if (m.multihit[0] !== 2 || m.multihit[1] !== 5) throw new Error(`multihit ${m.id}`);
    multihit = 25;
  } else if (m.multihit) multihit = m.multihit;
  let damage = 0;
  if (m.damage === 'level') damage = 255; else if (m.damage) damage = m.damage;
  const secStr = sec ? `Some(Secondary { chance: ${sec.chance ?? 0}, status: ${idx(STATUS, sec.status, 'status')}, volatile: ${idx(VOLATILES, sec.volatileStatus, 'volatile')}, boosts: ${boosts(sec.boosts)} })` : 'None';
  const fields = [
    `num: ${m.num}`,
    `id: ${JSON.stringify(m.id)}`,
    `name: ${JSON.stringify(m.name)}`,
    `type_: ${typeId(m.type)}`,
    `category: ${idx(CATS, m.category, 'category')}`,
    `base_power: ${m.basePower}`,
    `accuracy: ${m.accuracy === true ? 0 : m.accuracy}`,
    `pp: ${m.pp}`,
    `priority: ${m.priority}`,
    `target: ${idx(TARGETS, m.target, 'target')}`,
    `crit_ratio: ${m.critRatio || 1}`,
    `multihit: ${multihit}`,
    `recoil: [${m.recoil ? m.recoil.join(', ') : '0, 0'}]`,
    `drain: ${!!m.drain}`,
    `status: ${idx(STATUS, m.status, 'status')}`,
    `volatile: ${idx(VOLATILES, m.volatileStatus, 'volatile')}`,
    `self_volatile: ${idx(VOLATILES, m.self && m.self.volatileStatus, 'self volatile')}`,
    `boosts: ${boosts(m.boosts)}`,
    `secondary: ${secStr}`,
    `ohko: ${!!m.ohko}`,
    `damage: ${damage}`,
    `selfdestruct: ${!!m.selfdestruct}`,
    `ignore_immunity: ${m.ignoreImmunity === true}`,
    `will_crit: ${m.willCrit === false ? 0 : m.willCrit ? 1 : 2}`,
    `metronome: ${!!m.flags.metronome}`,
  ];
  w(`    MoveData { ${fields.join(', ')} },`);
}
w('];');
w('');
// Metronome's candidate list exactly as gen1 `metronome.onHit` builds it.
const metro = d.moves.all().filter(m => (!m.isNonstandard || m.isNonstandard === 'Unobtainable') && m.flags['metronome'])
  .sort((a, b) => a.num - b.num).map(m => m.num);
w('/// Metronome candidates in the order Showdown samples from (sorted by number).');
w(`pub static METRONOME: [u8; ${metro.length}] = [${metro.join(', ')}];`);
w('');
// Showdown's name aliases (data/aliases.ts) that resolve to a Gen 1 species or move, e.g.
// `hijumpkick` -> `highjumpkick`, `vicegrip` -> `visegrip`: Showdown accepts them in team sets.
const {Aliases} = require(path.resolve(psDir, 'dist/data/aliases.js'));
const toID = s => ('' + s).toLowerCase().replace(/[^a-z0-9]+/g, '');
const aliases = [];
for (const [alias, target] of Object.entries(Aliases)) {
  const m = d.moves.get(target);
  const s = d.species.get(target);
  if (m.exists && m.num >= 1 && m.num <= 165 && toID(target) === m.id) aliases.push([toID(alias), m.id]);
  else if (s.exists && s.num >= 1 && s.num <= 151 && !s.forme && toID(target) === s.id) aliases.push([toID(alias), s.id]);
}
aliases.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));
w('/// Showdown name aliases (ID -> canonical species/move ID) for Gen 1 species and moves.');
w(`pub static ALIASES: [(&str, &str); ${aliases.length}] = [`);
for (const [a, t] of aliases) w(`    (${JSON.stringify(a)}, ${JSON.stringify(t)}),`);
w('];');
console.log(out.join('\n'));
