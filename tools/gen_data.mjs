// Generates crates/battle-env/src/data/generated.rs from:
//   - the pinned pkmn engine (species/move ids, base stats, types, move data, type chart), and
//   - Pokémon Showdown's gen1 data (learnsets and Gen 1 random-battle sets; MIT licensed).
//
// Usage: node tools/gen_data.mjs <path-to-node_modules/pokemon-showdown>
// The output is checked in, so this only needs re-running when the engine or PS data changes.
import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ENGINE = path.join(ROOT, 'third_party/pkmn-engine');
const psPath = process.argv[2];
if (!psPath) {
  console.error('usage: node tools/gen_data.mjs <path-to-pokemon-showdown-package>');
  process.exit(1);
}
const require = createRequire(import.meta.url);
const PS = require(path.resolve(psPath));
const psVersion = JSON.parse(fs.readFileSync(path.join(psPath, 'package.json'), 'utf8')).version;
const dex = PS.Dex.forGen(1);
const randbats = JSON.parse(
  fs.readFileSync(path.join(psPath, 'dist/data/random-battles/gen1/data.json'), 'utf8'));

const toID = s => s.toLowerCase().replace(/[^a-z0-9]/g, '');

const [gen1] = JSON.parse(fs.readFileSync(path.join(ENGINE, 'src/data/data.json'), 'utf8'));
const types = gen1.types; // index == pkmn Type enum
const species = Object.entries(gen1.species); // index+1 == pkmn Species enum
const moves = Object.entries(gen1.moves); // index+1 == pkmn Move enum

// Parse move data (bp/type/accuracy/effect) from the engine's generated Zig source.
const movesZig = fs.readFileSync(path.join(ENGINE, 'src/lib/gen1/data/moves.zig'), 'utf8');
const dataBlock = movesZig.slice(movesZig.indexOf('const DATA = [_]Data{'));
const entryRe =
  /\/\/ (\w+)\s*\.\{\s*\.effect = \.(\w+),\s*\.bp = (\d+),\s*\.type = \.(\w+),\s*\.accuracy = percent\((\d+)\),\s*\.target = \.(\w+),/g;
const moveData = [...dataBlock.matchAll(entryRe)].map(m => ({
  name: m[1], effect: m[2], bp: +m[3], type: m[4], acc: +m[5], target: m[6],
}));
if (moveData.length !== moves.length) {
  throw new Error(`parsed ${moveData.length} moves, expected ${moves.length}`);
}
for (let i = 0; i < moves.length; i++) {
  if (toID(moves[i][0]) !== toID(moveData[i].name)) {
    throw new Error(`move mismatch at ${i}: ${moves[i][0]} vs ${moveData[i].name}`);
  }
}
const effects = [...new Set(moveData.map(m => m.effect))];

// Type chart.
const typesZig = fs.readFileSync(path.join(ENGINE, 'src/lib/gen1/data/types.zig'), 'utf8');
const EFF = {S: 20, N: 10, R: 5, I: 0};
const chart = [...typesZig.matchAll(/\[_\]Effectiveness\{([^}]*)\}/g)]
  .map(m => m[1].split(',').map(s => s.trim()).filter(Boolean).map(s => EFF[s]));
if (chart.length !== 15 || chart.some(r => r.length !== 15)) throw new Error('bad type chart');

// Learnsets: union of gen-1 sources over the evolution chain (prevos can pass moves down).
const moveIndex = new Map(moves.map(([n], i) => [toID(n), i + 1]));
const BLOCKED = new Set(['mimic', 'metronome', 'mirrormove', 'transform', 'struggle']);
function learnset(name) {
  const out = new Set();
  let s = dex.species.get(name);
  while (s && s.exists) {
    const data = dex.species.getLearnsetData(s.id);
    for (const [move, sources] of Object.entries(data.learnset || {})) {
      if (sources.some(src => src.startsWith('1')) && moveIndex.has(move)) out.add(move);
    }
    s = s.prevo ? dex.species.get(s.prevo) : null;
  }
  return [...out].map(m => moveIndex.get(m)).sort((a, b) => a - b);
}

const q = s => JSON.stringify(s);
let rs = `// @generated by tools/gen_data.mjs from pkmn/engine data and pokemon-showdown ${psVersion}.\n`;
rs += '// Do not edit by hand.\n\n';
rs += `pub const NUM_TYPES: usize = ${types.length};\n`;
rs += `pub const NUM_SPECIES: usize = ${species.length};\n`;
rs += `pub const NUM_MOVES: usize = ${moves.length};\n\n`;
rs += `pub static TYPE_NAMES: [&str; ${types.length}] = [${types.map(q).join(', ')}];\n\n`;
rs += '/// TYPE_CHART[attacking][defending] in {0, 5, 10, 20} (x10 multiplier).\n';
rs += `pub static TYPE_CHART: [[u8; 15]; 15] = [\n${chart.map(r => `    [${r.join(', ')}],`).join('\n')}\n];\n\n`;
rs += '/// Index 0 is the "None" sentinel; index i is pkmn Species i.\n';
rs += `pub static SPECIES_NAMES: [&str; ${species.length + 1}] = [\n    "None",\n`;
rs += species.map(([n]) => `    ${q(n)},`).join('\n') + '\n];\n\n';
rs += '/// Base stats [hp, atk, def, spe, spc].\n';
rs += `pub static SPECIES_BASE: [[u8; 5]; ${species.length + 1}] = [\n    [0, 0, 0, 0, 0],\n`;
rs += species.map(([, d]) => `    [${['hp', 'atk', 'def', 'spe', 'spc'].map(k => d.stats[k]).join(', ')}],`)
  .join('\n') + '\n];\n\n';
rs += `pub static SPECIES_TYPES: [[u8; 2]; ${species.length + 1}] = [\n    [0, 0],\n`;
rs += species.map(([, d]) => {
  const t = d.types.map(x => types.indexOf(x));
  return `    [${t[0]}, ${t[1] ?? t[0]}],`;
}).join('\n') + '\n];\n\n';
rs += '/// Move effects as named by the engine (index into MoveInfo::effect).\n';
rs += `pub static EFFECT_NAMES: [&str; ${effects.length}] = [${effects.map(q).join(', ')}];\n\n`;
rs += '#[derive(Clone, Copy, Debug)]\npub struct MoveInfo {\n';
rs += '    pub bp: u8,\n    pub ty: u8,\n    pub acc: u8,\n    pub pp: u8,\n    pub effect: u8,\n}\n\n';
rs += '/// Index 0 is the "None" sentinel; index i is pkmn Move i.\n';
rs += `pub static MOVE_NAMES: [&str; ${moves.length + 1}] = [\n    "None",\n`;
rs += moves.map(([n]) => `    ${q(n)},`).join('\n') + '\n];\n\n';
rs += `pub static MOVES: [MoveInfo; ${moves.length + 1}] = [\n`;
rs += '    MoveInfo { bp: 0, ty: 0, acc: 0, pp: 0, effect: 0 },\n';
rs += moves.map(([, pp], i) => {
  const m = moveData[i];
  return `    MoveInfo { bp: ${m.bp}, ty: ${types.indexOf(m.type)}, acc: ${m.acc}, pp: ${pp}, effect: ${effects.indexOf(m.effect)} },`;
}).join('\n') + '\n];\n\n';
rs += '/// Gen 1 learnable moves per species (union over the evolution chain). Excludes Mimic,\n';
rs += '/// Metronome, Mirror Move and Transform, which pkmn cannot replicate faithfully in Showdown\n';
rs += '/// mode, and Struggle.\n';
rs += `pub static LEARNSETS: [&[u8]; ${species.length + 1}] = [\n    &[],\n`;
rs += species.map(([n]) => {
  const ls = learnset(n).filter(m => !BLOCKED.has(toID(moves[m - 1][0])));
  return `    &[${ls.join(', ')}],`;
}).join('\n') + '\n];\n\n';
const sets = species.map(([n], i) => [i + 1, randbats[toID(n)]]).filter(([, s]) => s && s.moves);
rs += '/// Pokémon Showdown Gen 1 random-battle sets: (species, level, candidate moves).\n';
rs += `pub static RANDBATS: [(u8, u8, &[u8]); ${sets.length}] = [\n`;
rs += sets.map(([sp, s]) => {
  const ms = [...new Set(s.moves.map(m => moveIndex.get(toID(m))).filter(Boolean))];
  return `    (${sp}, ${s.level ?? 100}, &[${ms.join(', ')}]),`;
}).join('\n') + '\n];\n';

const out = path.join(ROOT, 'crates/battle-env/src/data/generated.rs');
fs.writeFileSync(out, rs);
console.log(`wrote ${out}: ${species.length} species, ${moves.length} moves, ${sets.length} randbats sets`);
