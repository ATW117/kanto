#!/usr/bin/env node
// Generates crates/kanto-backend/src/sd/dex.rs: the Showdown dex names the BattleStream port needs
// beyond kanto-data's Gen 1 tables (what `Teams.unpack` resolves names against: the *base* dex).
//
// Usage: node tools/gen_sd_dex.js <path to pokemon-showdown package> > crates/kanto-backend/src/sd/dex.rs
'use strict';
const path = require('path');
const psDir = process.argv[2];
if (!psDir) {
  console.error('usage: gen_sd_dex.js <pokemon-showdown dir>');
  process.exit(2);
}
const {Dex, toID} = require(path.resolve(psDir, 'dist/sim'));
const version = require(path.resolve(psDir, 'package.json')).version;
const gen1 = Dex.mod('gen1');
const out = [];
const w = s => out.push(s);
const lit = s => JSON.stringify(s);
w(`// @generated by tools/gen_sd_dex.js from pokemon-showdown ${version}. Do not edit by hand.`);
w('#![allow(clippy::all)]');
w('');
// Base-dex `species.abilities['0']` per Gen 1 species number (what an empty packed ability becomes).
const ab0 = [''];
for (let n = 1; n <= 151; n++) {
  const sp = gen1.species.all().find(s => s.num === n && !s.forme);
  const base = Dex.species.get(sp.name);
  ab0.push(base.abilities['0'] || '');
}
w(`pub static ABILITY0: [&str; 152] = [${ab0.map(lit).join(', ')}];`);
const table = (name, list) => {
  const rows = list.filter(x => x.exists !== false).map(x => [x.id, x.name]).sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));
  // dedupe ids
  const seen = new Set();
  const uniq = rows.filter(r => !seen.has(r[0]) && seen.add(r[0]));
  w(`/// (id, name), sorted by id.`);
  w(`pub static ${name}: [(&str, &str); ${uniq.length}] = [`);
  for (const [id, n] of uniq) w(`    (${lit(id)}, ${lit(n)}),`);
  w('];');
};
table('ABILITIES', Dex.abilities.all());
table('ITEMS', Dex.items.all());
table('NATURES', Dex.natures.all());
table('MOVES', Dex.moves.all());
table('SPECIES', Dex.species.all());
process.stdout.write(out.join('\n') + '\n');
